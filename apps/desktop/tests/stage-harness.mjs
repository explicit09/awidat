#!/usr/bin/env node
/**
 * Stage harness screenshot gate (Phase-1 Task 8, parameterized over
 * template scenes in Phase-2 Task 7).
 *
 * Boots (or reuses) the desktop dev server, then for each case in
 * CASES loads the deterministic `/stage-harness` route at a frozen
 * clock time, waits for `document.title === "stage-harness-ready"`,
 * DOM-asserts the expected overlays landed, screenshots just the
 * program-frame element, and compares it against a committed
 * per-platform golden via ffmpeg SSIM (see `scripts/ssim-compare.sh`).
 * Before capture, the video's decoded content is verified in-page
 * against a frame-0 signature (with a re-seek recovery loop) — the known
 * CI flake is the pre-seek frame remaining the video's presented frame,
 * a state observed to stick across page loads in one browser session. A
 * failing compare still gets ONE evidence-preserving recapture, from a
 * FRESH browser launch; both attempts' SSIMs are printed and the
 * attempt-1 screenshot is kept. See comments in captureCase/runCase.
 *
 * A missing per-platform golden is a hard failure so the gate can never
 * silently self-seed in CI. To seed a new platform, run once locally with
 * STAGE_GOLDEN_BOOTSTRAP=1 (or commit the screenshot CI uploads as the
 * `stage-harness-screenshots` artifact) and commit the golden.
 *
 * Template scene fixtures (`scene-lower-third.json`,
 * `scene-kinetic-text.json`) are generated by the sync tests in
 * `crates/core/tests/motion_template_goldens.rs` from
 * `expand_template` + the snapshot lowering's field mapping — do not
 * hand-edit them; regenerate with UPDATE_GOLDENS=1 there. Two
 * timestamps per template catch mid-animation states (slide-in in
 * flight vs settled; words mid-pop vs held).
 *
 * Follows the dev-server boot/reuse pattern of `tests/desktop-ui-smoke.mjs`
 * (canReachApp / ensureAppServer / stopAppServer), spawning
 * `pnpm --dir apps/desktop exec vite` when the app isn't already up.
 */

