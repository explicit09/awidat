const REPO_ROOT = fileURLToPath(new URL("../../..", import.meta.url));
const BASE_URL = process.env.SMOKE_URL ?? "http://127.0.0.1:1420/";
const APP_URL = new URL(BASE_URL);
const APP_PORT = APP_URL.port || (APP_URL.protocol === "https:" ? "443" : "80");
const SCREENSHOT_DIR = process.env.SMOKE_OUT_DIR ?? "tests/smoke";
const GOLDEN_DIR = "tests/fixtures/stage-golden";
mkdirSync(SCREENSHOT_DIR, { recursive: true });
mkdirSync(GOLDEN_DIR, { recursive: true });

const MIN_SSIM = "0.98";

/** Shared context options — the retry path launches a fresh browser and
 * must match the primary context exactly or goldens won't compare. */
const CONTEXT_OPTIONS = {
  viewport: { width: 1280, height: 720 },
  deviceScaleFactor: 1,
};

/**
 * In-page video content check threshold (mean absolute luminance
 * difference on a 32x18 downsample, 0-255 scale). Calibrated against the
 * fixture clip with ffmpeg: the stale frame (frame 0) vs itself is ~0 and
 * vs its neighbor frame 1 is 0.53, while frame 0 vs each case's target
 * frame is 2.23 (t=0.4) / 3.09 (t=0.5) / 7.53 (t=1.0) / 7.66 (t=1.5) /
 * 6.42 (t=2.0) — so 1.0 separates "still showing frame 0" from "showing
 * the seeked frame" with >= 2x margin on both sides for every case.
 */
const FRAME0_LUMA_DIFF_THRESHOLD = 1.0;
const MAX_RESEEKS = 5;

const MOTION_TITLE_SELECTOR = ".timeline-motion-scene-layer .timeline-title-overlay";
const LEGACY_TITLE_SELECTOR = ".timeline-title-layer .timeline-title-overlay";
const SHAPE_SELECTOR = ".timeline-motion-shape-rect";
const IMAGE_SELECTOR = ".timeline-motion-image";

async function overlayTexts(page, selector) {
  const layer = page.locator(selector);
  const count = await layer.count();
  const texts = [];
  for (let index = 0; index < count; index += 1) {
    texts.push((await layer.nth(index).textContent()) ?? "");
  }
  return texts;
}

async function assertOverlayCounts(page, { legacyTitles, motionTitles, shapes, images }) {
  assert.equal(
    await page.locator(LEGACY_TITLE_SELECTOR).count(),
    legacyTitles,
    `expected ${legacyTitles} legacy title overlay(s)`,
  );
  assert.equal(
    await page.locator(MOTION_TITLE_SELECTOR).count(),
    motionTitles,
    `expected ${motionTitles} motion-scene title overlay(s)`,
  );
  assert.equal(
    await page.locator(SHAPE_SELECTOR).count(),
    shapes,
    `expected ${shapes} shape overlay(s)`,
  );
  assert.equal(
    await page.locator(IMAGE_SELECTOR).count(),
    images,
    `expected ${images} image overlay(s)`,
  );
}

/** Phase-1 scene: one legacy title + one rect + one image. */
async function assertSceneBasic(page) {
  await assertOverlayCounts(page, { legacyTitles: 1, motionTitles: 0, shapes: 1, images: 1 });
  const [titleText] = await overlayTexts(page, LEGACY_TITLE_SELECTOR);
  assert.ok(titleText.includes("STAGE HARNESS"), `title overlay text mismatch: ${titleText}`);
}

/** Lower third: accent bar + name + role, at both timestamps (the bar
 * slides but never leaves its 0..5s window; both texts are staggered
 * in by 0.16s, so all three overlays exist at t=0.4 and t=2.0). */
async function assertLowerThird(page) {
  await assertOverlayCounts(page, { legacyTitles: 0, motionTitles: 2, shapes: 1, images: 0 });
  const texts = await overlayTexts(page, MOTION_TITLE_SELECTOR);
  assert.deepEqual(texts, ["Ada Lovelace", "Mathematician"], "lower-third text overlays mismatch");
}

/** Kinetic text: word layers have their own windows, so the visible
 * word set is timestamp-specific. */
function assertKineticWords(expectedWords) {
  return async (page) => {
    await assertOverlayCounts(page, {
      legacyTitles: 0,
      motionTitles: expectedWords.length,
      shapes: 0,
      images: 0,
    });
    const texts = await overlayTexts(page, MOTION_TITLE_SELECTOR);
    assert.deepEqual(texts, expectedWords, "kinetic-text word overlays mismatch");
  };
}

